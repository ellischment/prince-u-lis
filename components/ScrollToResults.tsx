"use client";

import { useEffect } from "react";

/**
 * Подводит подборку занятий к верху экрана после выбора в анкете «Чем займёмся».
 *
 * Зачем, если у ссылок есть якорь. Якорь работает только при переходе кликом.
 * При открытии готовой ссылки (`/?zadacha=practice#podborka` — такую можно
 * прислать в мессенджере или сохранить) браузер ищет элемент раньше, чем
 * страница дорисуется, не находит и остаётся наверху: проверено на боевом,
 * `scrollY` оставался 0, а подборка была на 1900px ниже экрана. Гость видел
 * первый экран и решал, что ничего не произошло.
 *
 * Компонент рисуется только когда выбран повод, и с `key={task}`, поэтому при
 * смене кнопки он пересоздаётся и прокрутка повторяется.
 *
 * Плавность берётся из `scroll-behavior: smooth` в globals.css, а он отключён
 * при `prefers-reduced-motion` — отдельной проверки здесь не нужно.
 * Ссылки остаются обычными ссылками: без JavaScript подборка всё равно
 * отфильтруется на сервере, просто без подводки.
 */
export function ScrollToResults({ targetId }: { targetId: string }) {
  useEffect(() => {
    const el = document.getElementById(targetId);
    if (!el) return;

    // Два кадра, а не сразу: к моменту эффекта разметка уже есть, но карточки
    // могут дорисовываться, и прокрутка уехала бы не туда.
    const id = requestAnimationFrame(() => {
      requestAnimationFrame(() => el.scrollIntoView({ block: "start" }));
    });
    return () => cancelAnimationFrame(id);
  }, [targetId]);

  return null;
}
