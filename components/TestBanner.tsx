import styles from "./TestBanner.module.css";

/**
 * Полоса «это проверочная версия» для тестового домена.
 *
 * Условие то же, что закрывает сайт от поисковиков: NEXT_PUBLIC_NOINDEX=1
 * (app/robots.ts, next.config.ts). На боевом домене переменная пустая, значит
 * полосы там не будет никогда, и отдельного выключателя не нужно, забыть его
 * снять невозможно. Переменная вшивается при сборке, поэтому проверка чисто
 * серверная и в клиентский бандл ничего лишнего не тянет.
 *
 * Нужна затем, что часть разделов студия ещё не заполнила: без предупреждения
 * пустой каталог и пустое расписание читаются как поломка сайта, а не как
 * незаполненные данные.
 */
export function TestBanner() {
  if (process.env.NEXT_PUBLIC_NOINDEX !== "1") return null;

  return (
    <div className={styles.bar} role="status">
      <b>Проверочная версия сайта.</b> Часть разделов студия ещё наполняет:
      расписание, отзывы, события и каталог пока пустые.
      <span className={styles.note}>
        Это не поломка. Настоящий адрес сайта будет princulissart.ru.
      </span>
    </div>
  );
}
