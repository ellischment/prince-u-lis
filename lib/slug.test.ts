// Транслитерация — только подсказка для панели (lib/slug.ts), администратор
// может поправить адрес вручную перед сохранением. Коллизии сам slugify не
// решает, тест это документирует, а не выдумывает несуществующее поведение.

import { describe, it, expect } from "vitest";
import { slugify } from "./slug";

describe("slugify", () => {
  it("транслитерирует кириллицу, пробел заменяет дефисом", () => {
    expect(slugify("Гончарный круг для начинающих")).toBe(
      "goncharnyy-krug-dlya-nachinayushchikh",
    );
  });

  it("твёрдый и мягкий знак выбрасывает, а не заменяет символом", () => {
    expect(slugify("Подъезд")).toBe("podezd");
  });

  it("е и ё дают одинаковый результат: коллизия не решается автоматически", () => {
    expect(slugify("Ёлка")).toBe(slugify("Елка"));
  });

  it("несколько небуквенных подряд схлопываются в один дефис", () => {
    expect(slugify("Круг  (для двоих)!!")).toBe("krug-dlya-dvoikh");
  });

  it("дефис не остаётся ни в начале, ни в конце строки", () => {
    expect(slugify("«Витраж»")).toBe("vitrazh");
  });

  it("обрезает результат до 80 символов", () => {
    const long = "а".repeat(100);
    expect(slugify(long)).toHaveLength(80);
  });

  it("латиницу и цифры пропускает как есть", () => {
    expect(slugify("Мастер-класс 2 в стиле art")).toBe("master-klass-2-v-stile-art");
  });
});
